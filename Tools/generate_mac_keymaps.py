#!/usr/bin/env python3
"""Generates Sources/GenmaiMac/KeyCodeMapTables.swift from Mozc's data/preedit/mac-*.tsv.

Swift counterpart of mac/generate_mapping.py (which emits init_kanamap.h, init_specialkeymap.h and
init_specialcharmap.h for KeyCodeMap.mm).

Usage: Tools/generate_mac_keymaps.py [path/to/mozc/src] > Sources/GenmaiMac/KeyCodeMapTables.swift
"""
import os
import sys


def read(path):
  rows = []
  for line in open(path, encoding='utf-8'):
    columns = line.rstrip('\n').split('\t')
    if len(columns) != 2:
      continue
    rows.append((columns[0].strip(), columns[1].strip()))
  return rows


def key_name(key):
  if not key.startswith('kVK_'):
    key = 'kVK_ANSI_' + key
  return key


def swift_string(value):
  return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def special(value):
  # KeyEvent::SpecialKey enum names -> Swift protobuf case names.
  names = {
      'ENTER': 'enter', 'TAB': 'tab', 'SPACE': 'space', 'BACKSPACE': 'backspace', 'DEL': 'del',
      'ESCAPE': 'escape', 'HOME': 'home', 'PAGE_UP': 'pageUp', 'PAGE_DOWN': 'pageDown', 'END': 'end',
      'LEFT': 'left', 'RIGHT': 'right', 'DOWN': 'down', 'UP': 'up', 'DECIMAL': 'decimal',
      'MULTIPLY': 'multiply', 'ADD': 'add', 'DIVIDE': 'divide', 'SEPARATOR': 'separator',
      'SUBTRACT': 'subtract', 'EQUALS': 'equals', 'OFF': 'off', 'ON': 'on', 'COMMA': 'comma',
  }
  if value in names:
    return '.' + names[value]
  if value.startswith('F') and value[1:].isdigit():
    return '.f' + value[1:]
  if value.startswith('NUMPAD'):
    return '.numpad' + value[len('NUMPAD'):]
  raise ValueError(value)


def main():
  root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
      os.path.dirname(__file__), '..', 'Vendor', 'mozc', 'src')
  preedit = os.path.join(root, 'data', 'preedit')
  kana = read(os.path.join(preedit, 'mac-kana.tsv'))
  special_keys = read(os.path.join(preedit, 'mac-specialkeys.tsv'))
  special_chars = read(os.path.join(preedit, 'mac-specialchars.tsv'))

  print('// Generated by Tools/generate_mac_keymaps.py from Vendor/mozc/src/data/preedit/mac-{kana,specialkeys,')
  print('// specialchars}.tsv (the Swift counterpart of mac/generate_mapping.py). Do not edit.')
  print()
  print('import Carbon')
  print('import GenmaiProtocol')
  print()
  for name, shift in (('kKanaMap', False), ('kKanaMapShift', True)):
    print('let %s: [UInt16: String] = [' % name)
    for key, value in kana:
      is_shift = key.startswith('Shift ')
      if is_shift != shift:
        continue
      if is_shift:
        key = key[len('Shift '):]
      print('  UInt16(%s): %s,' % (key_name(key), swift_string(value)))
    print(']')
    print()
  print('let kSpecialKeyMap: [UInt16: Genmai_Commands_KeyEvent.SpecialKey] = [')
  for key, value in special_keys:
    print('  UInt16(%s): %s,' % (key_name(key), special(value)))
  print(']')
  print()
  print('let kSpecialCharMap: [unichar: Genmai_Commands_KeyEvent.SpecialKey] = [')
  for key, value in special_chars:
    print('  unichar(%s): %s,' % (key, special(value)))
  print(']')


if __name__ == '__main__':
  main()
