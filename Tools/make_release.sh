#!/bin/zsh
# Builds the installer package of the current version and (with --publish) publishes it as a GitHub release. The
# usual path is the GitHub Actions workflow (.github/workflows/release.yml), which does the same when the tag vX.Y.Z
# is pushed; this script is the local equivalent.
#
# The version is kProductVersion (Sources/GenmaiBase/VersionDef.swift); the release is tag vX.Y.Z with the asset
# Genmai.pkg (no version in the name, so that .../releases/latest/download/Genmai.pkg is the newest one). The IME and the settings find releases through the GitHub API (GenmaiAppRelease.latest: the
# highest vX.Y.Z release that is not a draft or pre-release and has a .pkg asset) and verify the downloaded package
# against the size and SHA-256 digest GitHub lists. Publishing a release is therefore all an update needs; bump
# kProductVersion first.
#
# Usage: Tools/make_release.sh [--skip-build] [--publish] [--notes <file>]
#   --skip-build    reuse build/Genmai.pkg (Tools/make_installer_pkg.sh)
#   --publish       tag HEAD as vX.Y.Z, push the tag and create the GitHub release (gh); requires a clean tree
#   --notes <file>  release notes (Markdown); default: notes generated by GitHub from the commits
#   PKG_SIGN_IDENTITY=<identity>  passed to make_installer_pkg.sh (a "Developer ID Installer" identity)
set -euo pipefail

ROOT=${0:A:h:h}
SKIP_BUILD=0
PUBLISH=0
NOTES=
while (( $# )); do
  case $1 in
    --skip-build) SKIP_BUILD=1 ;;
    --publish) PUBLISH=1 ;;
    --notes) NOTES=${2:?--notes needs a file}; shift ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
  shift
done

VERSION=$(sed -n 's/.*kProductVersion = "\(.*\)"/\1/p' "$ROOT/Sources/GenmaiBase/VersionDef.swift")
TAG=v$VERSION
ASSET=$ROOT/build/Genmai.pkg
REPOSITORY=subdiox/genmai-ime  # GenmaiAppRelease.repository

if (( PUBLISH )); then
  if [[ -n $(git -C "$ROOT" status --porcelain) ]]; then
    echo "error: the working tree is not clean" >&2
    exit 1
  fi
  if gh release view "$TAG" -R $REPOSITORY >/dev/null 2>&1; then
    echo "error: release $TAG exists already (bump kProductVersion)" >&2
    exit 1
  fi
fi

if (( SKIP_BUILD )); then
  "$ROOT/Tools/make_installer_pkg.sh" --skip-build
else
  "$ROOT/Tools/make_installer_pkg.sh"
fi
echo "==> $ASSET ($(stat -f%z "$ASSET") bytes, sha256 $(shasum -a 256 "$ASSET" | cut -d' ' -f1))"

if (( ! PUBLISH )); then
  echo "Not published (pass --publish)."
  exit 0
fi

echo "==> tag $TAG"
if ! git -C "$ROOT" rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
  git -C "$ROOT" tag -a "$TAG" -m "Genmai $VERSION"
fi
git -C "$ROOT" push origin "$TAG"

echo "==> GitHub release $TAG"
if [[ -n $NOTES ]]; then
  gh release create "$TAG" "$ASSET" -R $REPOSITORY --title "Genmai $VERSION" --notes-file "$NOTES" --verify-tag
else
  gh release create "$TAG" "$ASSET" -R $REPOSITORY --title "Genmai $VERSION" --generate-notes --verify-tag
fi
gh release view "$TAG" -R $REPOSITORY --json url,assets --jq '.url, (.assets[] | "\(.name) \(.size) \(.digest)")'
