#!/usr/bin/env python3
"""Generates Sources/GenmaiGUI/Base/GUIStrings.swift from Mozc's Qt translation sources (gui/**/*_ja.qtts).

Usage: Tools/generate_gui_strings.py [path/to/mozc/src] > Sources/GenmaiGUI/Base/GUIStrings.swift

The Swift GUI looks strings up by (Qt context, English source text), exactly like QObject::tr(). English is the
source text itself; Japanese comes from the .qtts files. "[ProductName]" is substituted at runtime.
"""
import glob
import os
import sys
import xml.etree.ElementTree as ET

def swift_literal(s):
  out = []
  for ch in s:
    if ch == '\\':
      out.append('\\\\')
    elif ch == '"':
      out.append('\\"')
    elif ch == '\n':
      out.append('\\n')
    elif ch == '\t':
      out.append('\\t')
    elif ord(ch) < 0x20:
      out.append('\\u{%x}' % ord(ch))
    else:
      out.append(ch)
  return '"' + ''.join(out) + '"'

def main():
  root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
      os.path.dirname(__file__), '..', 'Vendor', 'mozc', 'src')
  table = {}
  files = sorted(glob.glob(os.path.join(root, 'gui', '**', '*_ja.qtts'), recursive=True))
  for path in files:
    tree = ET.parse(path)
    for context in tree.getroot().iter('context'):
      name = context.findtext('name')
      # Qt contexts are namespaced mozc::gui::X upstream; the Swift GUI uses genmai::gui::X.
      if name.startswith('mozc::'):
        name = 'genmai::' + name[len('mozc::'):]
      entries = table.setdefault(name, {})
      for message in context.iter('message'):
        source = message.findtext('source') or ''
        translation = message.find('translation')
        if translation is None or translation.get('type') in ('obsolete', 'vanished'):
          continue
        text = translation.text or ''
        numerus = translation.findall('numerusform')
        if numerus:
          text = numerus[0].text or ''
        if not text:
          continue
        entries.setdefault(source, text)
  print('// Generated by Tools/generate_gui_strings.py from Vendor/mozc/src/gui/**/*_ja.qtts. Do not edit.')
  print('// [context: [English source: Japanese translation]]')
  print()
  print('let kJapaneseTranslations: [String: [String: String]] = [')
  for name in sorted(table):
    print('  %s: [' % swift_literal(name))
    for source in sorted(table[name]):
      print('    %s: %s,' % (swift_literal(source), swift_literal(table[name][source])))
    print('  ],')
  print(']')

if __name__ == '__main__':
  main()
