/// `mozc::converter::Attribute`: bit flags of `Candidate.attributes`.
///
/// The C++ class wraps an unscoped enum so that the values convert implicitly
/// to integers for bitwise operations; in Swift they are `UInt32` constants.
public enum Attribute {
  public static let defaultAttribute: UInt32 = 0
  // this was the best candidate before learning
  public static let bestCandidate: UInt32 = 1 << 0
  // this candidate was reranked by user
  public static let reranked: UInt32 = 1 << 1
  // don't save it in history
  public static let noHistoryLearning: UInt32 = 1 << 2
  // don't save it in suggestion
  public static let noSuggestLearning: UInt32 = 1 << 3
  // NO_HISTORY_LEARNING | NO_SUGGEST_LEARNING
  public static let noLearning: UInt32 = (1 << 2 | 1 << 3)
  // learn it with left/right context
  public static let contextSensitive: UInt32 = 1 << 4
  // has "did you mean"
  public static let spellingCorrection: UInt32 = 1 << 5
  // No need to have full/half width expansion
  public static let noVariantsExpansion: UInt32 = 1 << 6
  // No need to have extra descriptions
  public static let noExtraDescription: UInt32 = 1 << 7
  // was generated by real-time conversion
  public static let realtimeConversion: UInt32 = 1 << 8
  // contains tokens in user dictionary.
  public static let userDictionary: UInt32 = 1 << 9
  // command candidate. e.g., incognito mode.
  public static let commandCandidate: UInt32 = 1 << 10
  // key characters are consumed partially.
  // Consumed size is |consumed_key_size|.
  // If not set, all the key characters are consumed.
  public static let partiallyKeyConsumed: UInt32 = 1 << 11
  // Typing correction candidate.
  // - Special description should be shown when the candidate is created
  //   by a dictionary predictor.
  // - No description should be shown when the candidate is loaded from
  //   history.
  // - Otherwise following unexpected behavior can be observed.
  //   1. Type "やんしょん" and submit "マンション" (annotated with "補正").
  //   2. Type "まんしょん".
  //   3. "マンション" (annotated with "補正") is shown as a candidate
  //      regardless of a user's correct typing.
  public static let typingCorrection: UInt32 = 1 << 12
  // Auto partial suggestion candidate.
  // - Special description should be shown when the candidate is created
  //   by a dictionary predictor.
  // - No description should be shown when the candidate is loaded from
  //   history.
  public static let autoPartialSuggestion: UInt32 = 1 << 13
  // Predicted from user prediction history.
  public static let userHistoryPrediction: UInt32 = 1 << 14
  // Contains suffix dictionary.
  public static let suffixDictionary: UInt32 = 1 << 15
  // Disables modification and removal in rewriters.
  public static let noModification: UInt32 = 1 << 16
  // Candidate which is reranked by user segment history rewriter.
  public static let userSegmentHistoryRewriter: UInt32 = 1 << 17
  // Keys are expanded in the dictionary lookup. Usually
  // Kana-modifiers are expanded.
  public static let keyExpandedInDictionary: UInt32 = 1 << 18
  // No-deletable candidate.
  // User history is basically deletable, but decoder can set NO_DELETABLE
  // attribute not to allow the candidate to be deleted.
  public static let noDeletable: UInt32 = 1 << 19

  // Prediction types (originally defined as PredictionType in
  // prediction/result.h)
  // Suggests from current key user is now typing.
  public static let unigram: UInt32 = 1 << 20
  // Suggests from the previous history key user typed before.
  // UserHistoryPredictor may also assign BIGRAM attribute.
  public static let bigram: UInt32 = 1 << 21
  // Add English words.
  public static let english: UInt32 = 1 << 22
  // Entries from number decoder.
  public static let number: UInt32 = 1 << 23
  // Entries from single kanji dictionary.
  public static let singleKanji: UInt32 = 1 << 24
  // Typing completion generated by typing corrector.
  public static let typingCompletion: UInt32 = 1 << 25
  // Reranked or inserted by post corrector.
  public static let postCorrection: UInt32 = 1 << 26
  // Entries from a supplemental model.
  public static let supplementalModel: UInt32 = 1 << 27
  // Weak user history candidate which doesn't need to rank at the top.
  public static let weakUserHistoryPrediction: UInt32 = 1 << 28
  // Suggests from |converter_|. The difference from REALTIME is that it uses
  // the full converter with rewriter, history, etc.
  public static let realtimeTop: UInt32 = 1 << 29
  // Disables rescoring. Keeps the original cost.
  public static let disableRescoring: UInt32 = 1 << 30
  // Set when an older user history entry lacks inner boundary information.
  // This attribute conveys that the original user history had no inner
  // boundary. Special care is needed when a single segment placeholder
  // is used as the inner boundary for such entries.
  public static let userHistoryEmptyInnerSegmentBoundary: UInt32 = 1 << 31
}
