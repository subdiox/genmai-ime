// Port of mozc/src/converter/quality_regression_test_lib.{h,cc} (3.35.6354).
//
// Deviations from C++:
// - The C++ is a gtest fixture (TestWithTempUserProfile) whose test data comes
//   from a generated `kTestData[]` array (gen_quality_regression_test_data.py).
//   Here the data is passed in as `[TestCase]` and the gtest assertions
//   (EXPECT_LT) are returned as `Report.failures`, so that a Swift Testing
//   test can `#expect` them. LOG(INFO) lines are collected in `Report.logs`.
// - absl::btree_map keyed by label → Swift dictionary iterated in sorted key
//   order (same order as btree_map). std::sort of (float, string) pairs →
//   sort by (accuracy, line), the same lexicographic pair order.

import Foundation
import GenmaiBase

public enum QualityRegressionTest {
  /// One entry of `kTestData[]`: a TSV line and whether it is enabled.
  public struct TestCase: Sendable {
    public var enabled: Bool
    public var line: String

    public init(enabled: Bool, line: String) {
      self.enabled = enabled
      self.line = line
    }
  }

  public struct Report: Sendable {
    /// Messages of the EXPECT_LT checks that failed (enabled cases only).
    public var failures: [String] = []
    /// LOG(INFO) messages.
    public var logs: [String] = []
    public var numExecutedCases = 0
    public var numDisabledCases = 0
    public var numSkippedCases = 0
  }

  private typealias ResultTable = [String: [(Float, String)]]

  /// `kTestData[]` as generated by converter/gen_quality_regression_test_data.py
  /// from TSV files: '#' lines and empty lines are skipped; a 'DISABLED_'
  /// prefix on the label disables the entry (and is removed).
  public static func loadTestData(_ files: [String]) throws -> [TestCase] {
    var result: [TestCase] = []
    for file in files {
      guard let data = FileManager.default.contents(atPath: file) else {
        throw StatusError(.notFound, "Failed to read: \(file)")
      }
      // Split on LF bytes (Swift treats CR LF as one Character).
      for var bytes in data.split(separator: UInt8(ascii: "\n"), omittingEmptySubsequences: false) {
        if bytes.first == UInt8(ascii: "#") { continue }
        while bytes.last == UInt8(ascii: "\r") { bytes = bytes.dropLast() }
        if bytes.isEmpty { continue }
        let line = String(decoding: bytes, as: UTF8.self)
        if line.hasPrefix("DISABLED_") {
          result.append(TestCase(enabled: false, line: String(line.dropFirst("DISABLED_".count))))
        } else {
          result.append(TestCase(enabled: true, line: String(line)))
        }
      }
    }
    return result
  }

  public static func runTestForPlatform(
    _ platform: UInt32, _ util: QualityRegressionUtil?, _ testData: [TestCase]
  ) throws -> Report {
    guard let util else {
      throw StatusError.invalidArgument("util is null")
    }
    var results: ResultTable = [:]
    var disabledResults: ResultTable = [:]
    var report = Report()

    for (i, testCase) in testData.enumerated() {
      if i % 1000 == 0 {
        report.logs.append("Testing: \(i) \(testCase.line)")
      }
      let tsvLine = testCase.line
      var item = QualityRegressionUtil.TestItem()
      do {
        try item.parseFromTSV(tsvLine)
      } catch {
        throw StatusError(.failedPrecondition, "Failed to parse test item: \(tsvLine)")
      }
      if item.platform & platform == 0 {
        report.numSkippedCases += 1
        continue
      }
      var actualValue = ""
      let testResult: Bool
      do {
        testResult = try util.convertAndTest(item, &actualValue)
      } catch {
        throw StatusError.invalidArgument("Failed to test the entry: \(tsvLine)")
      }

      let line = "\(tsvLine)\tActual: \(actualValue)"
      // use "-1.0" as a dummy expected ratio
      let entry: (Float, String) = testResult ? (-1.0, line) : (Float(item.accuracy), line)
      if testCase.enabled {
        report.numExecutedCases += 1
        results[item.label, default: []].append(entry)
      } else {
        report.logs.append("DISABLED: \(testCase.line)")
        report.numDisabledCases += 1
        disabledResults[item.label, default: []].append(entry)
      }
    }

    examineResults(true, platform, results, &report)
    examineResults(false, platform, disabledResults, &report)

    let totalCases = report.numExecutedCases + report.numDisabledCases + report.numSkippedCases
    report.logs.append("Tested \(report.numExecutedCases) / \(totalCases) entries.")
    return report
  }

  /// If `enabled` is true, then actual conversion results are tested and any
  /// failure is reported as test failure. If false, actual conversion results
  /// don't affect test results but closable issues are reported.
  private static func examineResults(
    _ enabled: Bool, _ platform: UInt32, _ results: ResultTable, _ report: inout Report
  ) {
    let sortedResults = results.sorted { Array($0.key.utf8).lexicographicallyPrecedes($1.key.utf8) }
    for (label, labelResults) in sortedResults {
      let values = labelResults.sorted { a, b in
        if a.0 != b.0 { return a.0 < b.0 }
        return Array(a.1.utf8).lexicographicallyPrecedes(b.1.utf8)
      }
      var correct = 0
      var allPassed = true
      for (accuracy, line) in values {
        if accuracy < 0 {
          correct += 1
          continue
        }
        // Print failed example for failed label
        let actualRatio = 1.0 * Double(correct) / Double(values.count)
        if enabled {
          if !(Double(accuracy) < actualRatio) {
            report.failures.append("\(line) \(accuracy) \(actualRatio)")
          }
        } else {
          if Double(accuracy) < actualRatio {
            report.logs.append("PASSED (DISABLED): \(label): \(line)")
          } else {
            report.logs.append("FAILED (DISABLED): \(label): \(line)")
            allPassed = false
          }
        }
      }
      report.logs.append("Accuracy: \(label) \(1.0 * Double(correct) / Double(values.count))")
      if !enabled && allPassed {
        report.logs.append(
          "CLOSED ISSUE [platform = \(QualityRegressionUtil.getPlatformString(platform))]: "
            + "\(label) with \(values.count) cases")
      }
    }
  }
}
