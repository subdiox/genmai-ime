@testable import GenmaiCore

/// Simple immutable converter mock for the realtime conversion test.
private final class PredictionMockImmutableConverter: ImmutableConverterInterface,
  @unchecked Sendable
{
  var convertHandler: ((ConversionOptions, Segments) -> Bool)?

  func convert(_ options: ConversionOptions, _ segments: Segments) -> Bool {
    convertHandler?(options, segments) ?? false
  }

  static func convertImpl(_ options: ConversionOptions, _ segments: Segments) -> Bool {
    if segments.conversionSegmentsSize != 1 || segments.conversionSegment(0).key.isEmpty {
      return false
    }
    let key = segments.conversionSegment(0).key
    let segment = segments.mutableConversionSegment(0)
    let candidate = segment.addCandidate()
    candidate.value = key
    candidate.key = key
    return true
  }
}

/// `MockRealtimeDecoder` with `using RealtimeDecoder::RealtimeDecoder` and only
/// Decode mocked.
private final class DecodeOnlyMockRealtimeDecoder: RealtimeDecoder, @unchecked Sendable {
  var decodeHandler: ((ConversionRequest) -> [PredictionResult])?
  override func decode(_ request: ConversionRequest) -> [PredictionResult] {
    decodeHandler?(request) ?? []
  }
}

struct RealtimeDecoderTests {
  @Test func decode() throws {
    let converter = MockConverter()
    let immutableConverter = PredictionMockImmutableConverter()

    let decoder = RealtimeDecoder(immutableConverter, converter)

    let kKey = "わたしのなまえはなかのです"

    // Set up mock converter
    do {
      // Make segments like:
      // "わたしの"    | "なまえは" | "なかのです"
      // "Watashino" | "Namaeha" | "Nakanodesu"
      let segments = Segments()

      func addSegment(_ key: String, _ value: String) {
        let segment = segments.addSegment()
        segment.setKey(key)
        let candidate = segment.addCandidate()
        candidate.key = key
        candidate.value = value
      }

      addSegment("わたしの", "Watashino")
      addSegment("なまえは", "Namaeha")
      addSegment("なかのです", "Nakanodesu")

      var called = 0
      converter.startConversionHandler = { _, out in
        called += 1
        #expect(called == 1)
        out.assign(from: segments)
        return true
      }
    }
    // Set up mock immutable converter
    do {
      let segments = Segments()
      let segment = segments.addSegment()
      segment.setKey("わたしのなまえはなかのです")
      let candidate = segment.addCandidate()
      candidate.value = "私の名前は中野です"
      candidate.key = "わたしのなまえはなかのです"
      candidate.innerSegmentBoundary = buildInnerSegmentBoundary(
        [
          (12, 6, 9, 3),  // "わたしの, 私の", "わたし, 私"
          (12, 9, 9, 6),  // "なまえは, 名前は", "なまえ, 名前"
          (15, 12, 9, 6),  // "なかのです, 中野です", "なかの, 中野"
        ], candidate.key, candidate.value)
      #expect(candidate.innerSegmentBoundary.count == 3)
      immutableConverter.convertHandler = { _, out in
        out.assign(from: segments)
        return true
      }
    }

    // A test case with use_actual_converter_for_realtime_conversion being
    // false, i.e., realtime conversion result is generated by
    // ImmutableConverterMock.
    do {
      var options = ConversionOptions()
      options.maxConversionCandidatesSize = 10
      options.useActualConverterForRealtimeConversion = false
      options.requestType = .prediction

      let convreq = ConversionRequestBuilder().setOptions(options).build()

      let results = decoder.decode(convreq)
      try #require(results.count == 1)
      #expect(results[0].getPredictionTypesForTesting() == Attribute.realtimeConversion)
      #expect(results[0].key == kKey)
      #expect(results[0].innerSegmentBoundary.count == 3)
      #expect((results[0].attributes & Attribute.noVariantsExpansion) != 0)
    }

    // A test case with use_actual_converter_for_realtime_conversion being
    // true, i.e., realtime conversion result is generated by MockConverter.
    do {
      var options = ConversionOptions()
      options.maxConversionCandidatesSize = 10
      options.useActualConverterForRealtimeConversion = true
      options.requestType = .prediction

      let convreq = ConversionRequestBuilder().setOptions(options).build()
      let results = decoder.decode(convreq)

      // When |request.use_actual_converter_for_realtime_conversion| is true,
      // the extra label REALTIME_TOP is expected to be added.
      try #require(results.count == 2)
      var realtimeTopFound = false
      for result in results {
        #expect((result.attributes & Attribute.realtimeConversion) != 0)
        #expect((result.attributes & Attribute.noVariantsExpansion) != 0)
        if result.key == kKey && result.value == "WatashinoNamaehaNakanodesu"
          && result.innerSegmentBoundary.count == 3
        {
          #expect((result.attributes & Attribute.realtimeTop) != 0)
          realtimeTopFound = true
        }
      }
      #expect(realtimeTopFound)
    }

    // Test case when suppress_realtime_conversion_with_converter flag is true.
    do {
      var options = ConversionOptions()
      options.maxConversionCandidatesSize = 10
      options.useActualConverterForRealtimeConversion = true
      options.requestType = .prediction

      var request = Genmai_Commands_Request()
      request.decoderExperimentParams.suppressRealtimeConversionWithConverter = true

      let convreq = ConversionRequestBuilder()
        .setRequestView(request)
        .setOptions(options)
        .build()

      let results = decoder.decode(convreq)

      // Converter call is suppressed, so only 1 result from ImmutableConverter
      // is returned (no REALTIME_TOP).
      try #require(results.count == 1)
      #expect(results[0].getPredictionTypesForTesting() == Attribute.realtimeConversion)
      #expect(results[0].key == kKey)
    }
  }

  @Test func decodeSuffix() throws {
    let converter = MockConverter()
    let immutableConverter = PredictionMockImmutableConverter()

    let decoder = DecodeOnlyMockRealtimeDecoder(immutableConverter, converter)

    var results = [PredictionResult()]
    results[0].value = "さんに"
    results[0].key = "さんに"
    results[0].cost = 1000
    let expected = results

    for prefixRid: UInt16 in [0, 20, 100] {
      // Only called once as the result is cached.
      var called = 0
      decoder.decodeHandler = { req in
        called += 1
        let options = req.options()
        #expect(
          options.maxConversionCandidatesSize == 1 && !options.createPartialCandidates
            && !options.kanaModifierInsensitiveConversion
            && !options.useActualConverterForRealtimeConversion && options.bosId == prefixRid
            && ((prefixRid > 0) == options.disablePrefixPenalty)
            && req.key() == expected[0].key)
        return expected
      }

      for _ in 0..<10 {
        let convreq = ConversionRequestBuilder().build()
        let result = try #require(decoder.decodeSuffix(convreq, prefixRid, "さんに"))
        #expect(result.key == results[0].key)
        #expect(result.value == results[0].value)
        #expect(result.cost == results[0].cost)
      }
      #expect(called == 1)
    }
  }
}
